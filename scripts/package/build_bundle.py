def tar_xz(stage_parent, folder, archive):
    tar = subprocess.Popen(["tar", "-C", stage_parent, "--owner=0", "--group=0", "--numeric-owner", "-cf", "-", folder],
                           stdout=subprocess.PIPE)
    with open(archive, "wb") as out:
        xz = subprocess.run(["xz", "-T0", "-6", "-c"], stdin=tar.stdout, stdout=out)
    tar.stdout.close()
    if tar.wait() or xz.returncode:
        raise SystemExit("tar | xz failed")


def dir_size(path):
    return sum(os.path.getsize(os.path.join(b, f)) for b, _, fs in os.walk(path) for f in fs)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--target", choices=["arm64", "x86_64", "all"], default="arm64",
                   help="arm64: Raspberry Pi 4 and Jetson (ETC2/ASTC textures); x86_64: a PC (S3TC/BPTC); all: both")
    p.add_argument("--version", help="default: the date and the short commit, 2026.10.24-ab12cd3")
    p.add_argument("--out", default=os.path.join(ROOT, "dist"), help="where the archive goes (default dist/)")
    p.add_argument("--platform-addons", action="store_true",
                   help="no binary add-on (GoZen) in the bundle: the platform installs them; implied by --target all")
    p.add_argument("--no-archive", action="store_true", help="stop after staging; leave the folder")
    p.add_argument("--keep-stage", action="store_true")
    args = p.parse_args(argv)
    check_workspace()
    commit = git("rev-parse", "--short", "HEAD") or "nogit"
    version = args.version or "{}-{}".format(datetime.date.today().strftime("%Y.%m.%d"), commit)
    formats = FORMATS[args.target]
    platform_addons = args.platform_addons or args.target == "all"
    out = os.path.abspath(args.out)
    parent = os.path.join(out, "stage")
    stage = os.path.join(parent, NAME)
    if os.path.isdir(parent):
        fsutil.remove_dir(parent)
    os.makedirs(stage)
    say("== staging the files ({}, textures {})".format(args.target, formats))
    say("   {} files".format(stage_tree(stage, args.target, platform_addons)))
    bad = forbidden(stage)
    if bad:
        raise SystemExit("cabinet data in the bundle: " + ", ".join(bad))
    say("== Godot import for {} textures ({} VRAM-compressed frames)".format(formats, seed_imports(stage)))
    set_texture_formats(os.path.join(stage, "game", "project.godot"), formats)
    godot_import(os.path.join(stage, "game"), tc.godot_path())
    say("   dropped {} texture files of formats the target cannot use".format(
        prune_formats(os.path.join(stage, "game"), formats)))
    variants = count_variants(os.path.join(stage, "game"))
    say("   textures: " + ", ".join("{} {}".format(v, k or "lossless") for k, v in sorted(variants.items())))
    want = {"etc2": ("etc2", "astc"), "s3tc": ("s3tc", "bptc"), "both": ("etc2", "astc", "s3tc", "bptc")}[formats]
    if sum(v for k, v in variants.items() if k in want) < 1000:
        raise SystemExit("the import made no {} textures: {}".format(formats, variants))
    sizes = {"stage_bytes": dir_size(stage), "textures": variants}
    with open(os.path.join(stage, "bundle.json"), "w", encoding="utf-8") as f:
        json.dump(manifest(version, args.target, formats, sizes, stage, platform_addons), f, indent=2)
        f.write("\n")
    say("== SHA256SUMS: {} files".format(write_sums(stage)))
    if args.no_archive:
        say("staged in " + stage)
        return 0
    archive = os.path.join(out, "{}-{}-linux-{}.tar.xz".format(NAME, version, args.target))
    say("== " + archive)
    tar_xz(parent, NAME, archive)
    with open(archive + ".sha256", "w", encoding="utf-8") as f:
        f.write("{}  {}\n".format(sha256(archive), os.path.basename(archive)))
    say("   {:.0f} MB (unpacked {:.0f} MB)".format(os.path.getsize(archive) / 1e6, sizes["stage_bytes"] / 1e6))
    if not args.keep_stage:
        fsutil.remove_dir(parent)
    return 0


if __name__ == "__main__":
    sys.exit(main() or 0)
