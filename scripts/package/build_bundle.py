#!/usr/bin/env python3
"""Build the prebuilt game bundle (docs/bundle.md): the game as it runs, with nothing left to generate or import.

    python scripts/package/build_bundle.py                       # arm64 bundle (Raspberry Pi 4, Jetson) into dist/
    python scripts/package/build_bundle.py --target x86_64       # a PC
    python scripts/package/build_bundle.py --target all          # both texture formats, every GoZen build
    python scripts/package/build_bundle.py --version 2026.10.24 --out /some/folder

Needs a workspace that scripts/setup.py has finished (assets, generated config and media, fonts baked). The
bundle holds, under one folder `tron-legacy-mpf/`:

    bundle.json        what it is, what it needs, how to start it, where its data lives (docs/bundle.md)
    SHA256SUMS         every file's hash
    scripts/           run.py and the few scripts it imports, scripts/package/ (start, options)
    game/              the Godot project and MPF machine folder, generated config, media, sounds, fonts, and the
                       Godot import made again here for the target's texture format (game/.godot/)
    assets/            only the files the game reads at run time (not the decompile, rules, traces)
    pup_addons/        nothing; the GoZen video add-on is inside game/addons/

No ROM, no PuP Pack, no credentials: the pack is installed from its author's zip afterwards
(scripts/pup/pup_setup.py --pup-zip), the Scorbit keys and cabinet layout go in game/*.local.cfg.
Standard library only. The Godot import runs the workspace's Godot (about 4 minutes).
"""
import argparse
import datetime
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))   # scripts/
import fsutil  # noqa: E402
import gen_media  # noqa: E402  (HD_FRAME_IMPORT only)
import toolchain as tc  # noqa: E402
sys.path.insert(0, HERE)
import board_profile  # noqa: E402

ROOT = tc.ROOT
NAME = "tron-legacy-mpf"
FORMAT = 1

# scripts a started bundle imports (run.py -> gmc_patch, fsutil, toolchain, pup_setup -> gen_pup)
SCRIPTS = ["run.py", "toolchain.py", "fsutil.py", "gmc_patch.py", "pup/__init__.py", "pup/pup_setup.py",
           "pup/gen_pup.py", "package/__init__.py", "package/start.py", "package/bundle_options.py",
           "package/options.json", "package/board_profile.py", "package/profiles.json", "package/dmd_panel.py"]

# generated by scripts/setup.py, git-ignored: copied from the workspace next to the tracked files of game/
GENERATED = ["game/config/rom", "game/sounds", "game/media", "game/slides/deffs", "game/tron/media_data.json",
             "game/fonts", "game/fonts_ttf/baked", "game/addons/mpf-gmc"]

# what the game reads from assets/ at run time (found by running it under strace, tests/test_bundle.py keeps the list)
ASSET_FILES = ["assets/mpf_package/event_map.csv", "assets/mpf_package/lamp_effects.csv",
               "assets/mpf_package/service_menu.json", "assets/mpf_package/media/rom_images_all.zip"]
ASSET_DIRS = ["assets/mpf_package/config", "assets/rom_data/io", "assets/rom_data/pro", "assets/rom_data/settings",
              "assets/rom_data/deffs", "assets/io", "assets/callouts"]
# the frame timing of every display effect (the frames themselves are generated into game/media)
ASSET_GLOBS = [("assets/mpf_package/media/dmd", "timing.json")]

# never in a bundle: this cabinet's data, credentials, logs, caches
NEVER = ["game/data", "game/audits", "game/logs", "game/monitor/logs", "game/monitor/settings.ini",
         "game/monitor/settings.ini.lock", "game/pup.local.cfg", "game/scorbit.local.cfg", "game/options.json",
         "game/.godot"]
SKIP_NAMES = {"__pycache__", ".DS_Store", ".git"}
SKIP_SUFFIX = (".import", ".pyc", ".part", ".lock")

GOZEN_BINS = {"arm64": ["libgozen.linux.template_release.arm64.so"],
              "x86_64": ["libgozen.linux.template_release.x86_64.so", "libgozen.windows.template_release.x86_64.dll"]}
# VRAM texture formats Godot imports for each target: ARM GPUs (Pi 4's V3D, Jetson) take ETC2/ASTC, PCs S3TC/BPTC
FORMATS = {"arm64": "etc2", "x86_64": "s3tc", "all": "both"}


def say(text):
    print(text, flush=True)


def git(*args):
    r = subprocess.run(["git", "-C", ROOT] + list(args), capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def skip(rel):
    parts = rel.replace("\\", "/").split("/")
    return any(p in SKIP_NAMES for p in parts) or rel.endswith(SKIP_SUFFIX)


def copy_file(src_root, rel, dst_root):
    if skip(rel):
        return 0
    dst = os.path.join(dst_root, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(os.path.join(src_root, rel), dst)
    return 1


def copy_path(src_root, rel, dst_root):
    """A file or a whole folder (minus skipped names); returns the number of files copied."""
    src = os.path.join(src_root, rel)
    if not os.path.exists(src):
        return 0
    if os.path.isfile(src):
        return copy_file(src_root, rel, dst_root)
    n = 0
    for base, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in SKIP_NAMES]
        for name in files:
            n += copy_file(src_root, os.path.relpath(os.path.join(base, name), src_root), dst_root)
    return n


def tracked_game_files():
    out = git("ls-files", "-z", "game")
    return [p for p in out.split("\0") if p and not p.startswith("game/addons/")]


def check_workspace():
    problems = []
    if tc.media_stale():
        problems.append("the generated media are out of date: " + tc.media_stale())
    for rel in ("assets/mpf_package/service_menu.json", "game/config/rom", "game/media", "game/sounds",
                "game/addons/mpf-gmc/plugin.cfg", "game/fonts_ttf/baked", "pup_addons/gde_gozen/gozen.gdextension"):
        if not os.path.exists(os.path.join(ROOT, rel)):
            problems.append("missing " + rel)
    if problems:
        raise SystemExit("the workspace is not ready (run `python scripts/setup.py` first):\n  " + "\n  ".join(problems))


def stage_tree(stage, target, platform_addons=False):
    n = 0
    for rel in SCRIPTS:
        n += copy_file(os.path.join(ROOT, "scripts"), rel, os.path.join(stage, "scripts"))
    for rel in tracked_game_files():
        n += copy_file(ROOT, rel, stage)
    for rel in GENERATED:
        n += copy_path(ROOT, rel, stage)
    for rel in ASSET_FILES + ASSET_DIRS:
        n += copy_path(ROOT, rel, stage)
    for folder, name in ASSET_GLOBS:
        for d in sorted(os.listdir(os.path.join(ROOT, folder))):
            n += copy_path(ROOT, "{}/{}/{}".format(folder, d, name), stage)
    # GoZen (the PuP videos) into game/addons, only the builds of this target
    if platform_addons:
        return n  # the platform (MPF-Godot-Packaging) installs GoZen for the machine's own architecture
    gozen_src = os.path.join(ROOT, "pup_addons", "gde_gozen")
    gozen_dst = os.path.join(stage, "game", "addons", "gde_gozen")
    keep = set(sum((GOZEN_BINS[t] for t in (GOZEN_BINS if target == "all" else [target])), []))
    for base, dirs, files in os.walk(gozen_src):
        for name in files:
            rel = os.path.relpath(os.path.join(base, name), gozen_src)
            if rel.startswith("bin" + os.sep) and name not in keep and name != ".gdignore":
                continue
            dst = os.path.join(gozen_dst, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(os.path.join(base, name), dst)
            n += 1
    return n


def seed_imports(stage):
    """The .import files scripts/gen_media.py writes for the HD effect frames (VRAM-compressed): they are not
    tracked and are skipped when copying, so each is written again here before the import."""
    n = 0
    root = os.path.join(stage, "game", "media", "dmd_hd")
    for folder in sorted(d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d))):
        for name in sorted(os.listdir(os.path.join(root, folder))):
            if name.endswith(".png") and not name.startswith(("solid", "hollow")):
                with open(os.path.join(root, folder, name + ".import"), "w", encoding="utf-8", newline="\n") as f:
                    f.write(gen_media.HD_FRAME_IMPORT)
                n += 1
    return n


def count_variants(stage_game):
    """{suffix: files} of the .ctex in .godot/imported: '' for lossless, 'etc2', 's3tc', ..."""
    out = {}
    for name in os.listdir(os.path.join(stage_game, ".godot", "imported")):
        m = re.search(r"-[0-9a-f]{32}(?:\.(\w+))?\.ctex$", name)
        if m:
            out[m.group(1) or ""] = out.get(m.group(1) or "", 0) + 1
    return out


DROP = {"etc2": ("s3tc", "bptc"), "s3tc": ("etc2", "astc"), "both": ()}


def prune_formats(stage_game, formats):
    """Godot always imports the variant its host prefers (S3TC/BPTC on this PC), whatever the project setting says.
    A target that cannot use it would carry it for nothing, and a Jetson would pick it over ETC2 when it is listed
    in a texture's .import: take the dropped formats out of every .import and delete their .ctex files."""
    drop = DROP[formats]
    removed = 0
    for base, _, files in os.walk(stage_game):
        if ".godot" in os.path.relpath(base, stage_game).split(os.sep):
            continue
        for name in files:
            if not name.endswith(".import"):
                continue
            path = os.path.join(base, name)
            with open(path, encoding="utf-8") as f:
                text = f.read()
            if "path." not in text:
                continue
            out = []
            for line in text.split("\n"):
                m = re.match(r"path\.(\w+)=", line)
                if m and m.group(1) in drop:
                    continue
                if line.startswith("dest_files="):
                    items = [i for i in re.findall(r'"([^"]*)"', line)
                             if not any(i.endswith(".{}.ctex".format(d)) for d in drop)]
                    line = "dest_files=[{}]".format(", ".join('"{}"'.format(i) for i in items))
                if line.startswith('"imported_formats"'):
                    items = [i for i in re.findall(r'"(\w+)"', line.split(":", 1)[1])]
                    gone = {"s3tc": "s3tc_bptc", "bptc": "s3tc_bptc", "etc2": "etc2_astc", "astc": "etc2_astc"}
                    items = [i for i in items if i not in {gone[d] for d in drop}]
                    line = '"imported_formats": [{}],'.format(", ".join('"{}"'.format(i) for i in items))
                out.append(line)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write("\n".join(out))
    imported = os.path.join(stage_game, ".godot", "imported")
    for name in os.listdir(imported):
        if any(name.endswith(".{}.ctex".format(d)) for d in drop):
            os.remove(os.path.join(imported, name))
            removed += 1
    return removed


def set_texture_formats(project, formats):
    """Godot's import writes the VRAM-compressed variants this project setting names (default: S3TC/BPTC only)."""
    with open(project, encoding="utf-8") as f:
        text = f.read()
    etc2 = "true" if formats in ("etc2", "both") else "false"
    s3tc = "true" if formats in ("s3tc", "both") else "false"
    lines = ["textures/vram_compression/import_etc2_astc=" + etc2,
             "textures/vram_compression/import_s3tc_bptc=" + s3tc]
    text = re.sub(r"^textures/vram_compression/import_\w+=.*\n", "", text, flags=re.M)
    if "[rendering]\n" not in text:
        raise SystemExit("no [rendering] section in " + project)
    text = text.replace("[rendering]\n", "[rendering]\n\n" + "\n".join(lines) + "\n", 1)
    with open(project, "w", encoding="utf-8") as f:
        f.write(text)


def godot_import(stage_game, godot):
    """The import and the font bake, as scripts/setup.py does after generating the media."""
    for _ in range(2):          # the first pass can report add-on icon errors; the second is clean
        subprocess.run([godot, "--headless", "--path", stage_game, "--import"], stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL, timeout=1800)
    if not os.path.isdir(os.path.join(stage_game, ".godot", "imported")):
        raise SystemExit("the Godot import made no .godot/imported")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def forbidden(stage):
    """Anything in the staged tree that belongs to a cabinet, not to a release."""
    found = [rel for rel in NEVER if os.path.exists(os.path.join(stage, rel)) and rel != "game/.godot"]
    for base, _, files in os.walk(stage):
        for name in files:
            if name.endswith(".local.cfg") or name in ("machine_vars.yaml", "scorbit_device_key.txt"):
                found.append(os.path.relpath(os.path.join(base, name), stage))
    return found


def write_sums(stage):
    lines = []
    for base, dirs, files in os.walk(stage):
        dirs.sort()
        for name in sorted(files):
            path = os.path.join(base, name)
            rel = os.path.relpath(path, stage).replace(os.sep, "/")
            if rel != "SHA256SUMS":
                lines.append("{}  {}\n".format(sha256(path), rel))
    lines.sort(key=lambda l: l.split("  ", 1)[1])
    with open(os.path.join(stage, "SHA256SUMS"), "w", encoding="utf-8") as f:
        f.writelines(lines)
    return len(lines)


def gozen_features(stage):
    """{binary: [what it carries]} of the bundle's GoZen builds, read from their symbols: an installer keeps a
    build that has its board's decoder instead of putting another in its place."""
    marks = {"nvmpi": b"ff_h264_nvmpi_decoder", "v4l2m2m": b"ff_h264_v4l2m2m_decoder", "zero_copy": b"GOZEN_ZEROCOPY",
             "nv12": b"GOZEN_V4L2_PIXFMT"}
    out = {}
    bindir = os.path.join(stage, "game", "addons", "gde_gozen", "bin")
    for name in sorted(os.listdir(bindir)) if os.path.isdir(bindir) else ():
        if name.startswith("libgozen"):
            with open(os.path.join(bindir, name), "rb") as f:
                data = f.read()
            out[name] = [k for k, m in marks.items() if m in data]
    return out


